i = 1                   # Se inicializa i en 1
while i < 6:            # Se chequea si hay que ejecutar el cuerpo del ciclo
    print(i, end=" ")   # Se imprime i por la pantalla sin pasar a nueva línea
    i = i+1             # Se incrementa i; seguidamente, se evalúa otra vez la guarda
print()                 # Se imprime un línea antes de finalizar el programa
